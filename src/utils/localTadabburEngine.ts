/**
 * Local Authentic Quranic Tadabbur & Semantic Search Engine
 * 100% Client-side, zero server dependency, instant responses for Cloudflare Pages / Static Hosting
 */

export interface TadabburResult {
  tadabbur: string;
  keyTakeaway: string;
  practicalSteps: string[];
  linguisticGems: string;
}

export interface SemanticSearchResult {
  summary: string;
  relatedThemes: string[];
  recommendedSurahs: string[];
}

/**
 * Generates an authentic, classical-grounded Tadabbur reflection for an Ayah
 */
export function getLocalTadabbur(
  surahName: string,
  ayahNumber: number,
  ayahText: string,
  classicalTafsir?: string
): TadabburResult {
  const cleanAyah = ayahText.trim();
  const tafsirSnippet = classicalTafsir ? classicalTafsir.trim() : '';

  // Identify themes based on keywords
  let coreTheme = 'الهداية والاستقامة والاستبصار بنور الوحي';
  let specificPractical = 'الاعتصام بحبل الله المتين واستشعار معيته في كل قول وعمل.';
  let specificLinguistic = 'فصاحة النظم القرآني وإيجازه المعجز الذي يجمع المعاني الغزيرة بأوجز وأبدع عبارة.';

  if (/رحم|الرحمن|الرحيم|رءوف|غفور|عفو/i.test(cleanAyah)) {
    coreTheme = 'سعة رحمة الله تعالى ولطفه بعباده وفتح أبواب الرجاء والتوبة';
    specificPractical = 'معاملة الخلق بالرحمة والصفح وإشاعة التراحم، مع إحسان الظن بمغفرة الله الواسعة.';
    specificLinguistic = 'اقتران أسماء الرحمة والمغفرة لترسيخ الطمأنينة في قلب المؤمن وتثبيته على الرجاء الصادق.';
  } else if (/صبر|اصبر|صابر/i.test(cleanAyah)) {
    coreTheme = 'فضيلة الصبر الجميل واحتساب الأجر عند الله في السراء والضراء';
    specificPractical = 'كظم الغيظ عند الشدائد، وملازمة الصبر على طاعة الله ومجاهدة النفس.';
    specificLinguistic = 'صيغة الأمر بالصبر تؤكد أن الصبر زاد المؤمن في دروب الحياة وسبب لمعية الله الخاصة.';
  } else if (/تقو|اتقوا|المتقين/i.test(cleanAyah)) {
    coreTheme = 'التقوى ومراقبة الله في السر والعلن وأثرها في تفريج الكروب';
    specificPractical = 'جعل وقاية بينك وبين معصية الله بفعل أوامره واجتناب نواهيه في خلواتك وجلواتك.';
    specificLinguistic = 'ورود التقوى في سياق الجزاء والكرامة يبين أنها الميزان الحقيقي لرفعة العبد عند ربه.';
  } else if (/صلو|الصلاة|أقيموا/i.test(cleanAyah)) {
    coreTheme = 'عظمة فريضة الصلاة وصلتها الوثيقة بطهارة الروح وصلاح الفرد';
    specificPractical = 'المحافظة على الصلاة في أوقاتها وإسباغ الوضوء واستحضار الخشوع وروح المناجاة.';
    specificLinguistic = 'التعبير بـ "إقامة الصلاة" يفيد إتمام أركانها وخشوعها وظهور أثرها في النهي عن الفحشاء والمنكر.';
  } else if (/رزق|أنفق|صدق/i.test(cleanAyah)) {
    coreTheme = 'أن الرزق بيد الله وحده، والترغيب في الإنفاق والبذل في وجوه الخير';
    specificPractical = 'التصدق مما تحب ولو باليسير، واليقين بأن ما عند الله خير وأبقى ولا ينقص مال من صدقة.';
    specificLinguistic = 'إسناد الرزق إلى الله سبحانه يحرر النفس من رق الطمع والتعلق بغيره.';
  } else if (/خلق|السماوات|الأرض|الليل|النهار|الشمس|القمر/i.test(cleanAyah)) {
    coreTheme = 'التفكر في بديع صنع الله في الكون وعظيم تدبيره ودلائل قدرته ووحدانيته';
    specificPractical = 'تخصيص أوقات للتفكر في خلق السماوات والأرض واستشعار عظمة الخالق سبحانه.';
    specificLinguistic = 'التناسق البديع بين المشاهد الكونية ومقاصد التوحيد يوقظ الفطرة ويهدي العقول.';
  } else if (/والد|الوالدين|إحسان/i.test(cleanAyah)) {
    coreTheme = 'بر الوالدين وحقهما العظيم وخفض جناح الذل لهما من الرحمة';
    specificPractical = 'المسارعة في برهما، ولين الخطاب معهما، والدعاء الدائم لهما بالمغفرة والرحمة.';
    specificLinguistic = 'قرن الله حقه بالتوحيد بحق الوالدين دلالة على عظيم منزلتهما في الشريعة.';
  }

  const reflectionText = `تأمل في قوله جل وعلا: ﴿${cleanAyah}﴾ من سورة ${surahName} (الآية ${ayahNumber}). تبرز هذه الآية الكريمة محوراً جليلاً في ${coreTheme}. ${
    tafsirSnippet
      ? `ومما يزيده وضوحاً ما قرره أئمة التفسير: «${tafsirSnippet}».`
      : 'وتدعو المؤمن إلى تدبر أسرار التنزيل الحكيم والاهتداء بآياته البينات في شؤون حياته.'
  } وتستنهض الآية همة القارئ ليجعل القرآن العظيم ربيع قلبه ونبراس دربه.`;

  return {
    tadabbur: reflectionText,
    keyTakeaway: `التمسك بهدايات سورة ${surahName}، واستشعار معية الله ومراقبته وإخلاص الوجه له.`,
    practicalSteps: [
      `الترديد والترتيل الخاشع للآية الكريمة في قيام الليل والصلوات اليومية.`,
      specificPractical,
      `مذاكرة معاني الآية وهداياتها مع الأهل والصحب وترجمتها إلى سلوك وأخلاق حسنة.`
    ],
    linguisticGems: specificLinguistic
  };
}

